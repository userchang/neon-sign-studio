  function getVectorGlyph(ch) {
    if (!ch) return null;
    const key = ch.toUpperCase();
    return GLYPHS[key] || null;
  }

  function traceVectorGlyph(ctx, glyph, x, y, w, h) {
    ctx.beginPath();
    const strokes = glyph.s;
    for (let i = 0; i < strokes.length; i++) {
      const pts = strokes[i];
      if (!pts.length) continue;
      ctx.moveTo(x + pts[0][0] * w, y + pts[0][1] * h);
      for (let j = 1; j < pts.length; j++) {
        ctx.lineTo(x + pts[j][0] * w, y + pts[j][1] * h);
      }
    }
  }

